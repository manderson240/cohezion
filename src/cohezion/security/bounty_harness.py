"""Formal Invariant Verification Harness for Bug Bounties and Security Audits.

Extends Cohezion's AutoHarness (arXiv:2603.03329v1) with deterministic AST and
state-transition verifiers to detect high-severity invariant violations
(access control, checks-effects-interactions, arithmetic precision, oracle math)
for authorized bug-bounty programs and security assessments.
"""

from __future__ import annotations

import ast
import enum
import logging
import os
import time
from dataclasses import dataclass, field


logger = logging.getLogger(__name__)


class InvariantSeverity(enum.StrEnum):
    """Immunefi / CVSS severity levels for detected invariant failures."""

    INFORMATIONAL = "informational"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class InvariantCategory(enum.StrEnum):
    """Core formal invariant categories in smart contracts and agent systems."""

    ACCESS_CONTROL = "access_control"
    CHECKS_EFFECTS_INTERACTIONS = "checks_effects_interactions"
    ARITHMETIC_PRECISION = "arithmetic_precision"
    ORACLE_MANIPULATION = "oracle_manipulation"
    UNBOUNDED_RESOURCE = "unbounded_resource"
    STATE_DESYNCHRONIZATION = "state_desynchronization"
    ARBITRARY_EXECUTION = "arbitrary_execution"
    UNPROTECTED_INITIALIZER = "unprotected_initializer"


@dataclass(frozen=True, slots=True)
class InvariantViolation:
    """Detailed record of a formal invariant breach."""

    category: InvariantCategory
    severity: InvariantSeverity
    rule_name: str
    line_number: int
    description: str
    formal_proof_trace: str
    remediation_recommendation: str


@dataclass(slots=True)
class BountyAuditReport:
    """Structured report suitable for responsible disclosure under bug-bounty scope."""

    target_name: str
    analyzed_lines: int
    execution_time_ms: float
    violations: list[InvariantViolation] = field(default_factory=list)
    timestamp: float = field(default_factory=time.time)

    @property
    def is_clean(self) -> bool:
        """Return True if zero invariant violations were detected."""
        return len(self.violations) == 0

    @property
    def max_severity(self) -> InvariantSeverity:
        """Calculate highest severity among detected violations."""
        if not self.violations:
            return InvariantSeverity.INFORMATIONAL
        severity_order = [
            InvariantSeverity.INFORMATIONAL,
            InvariantSeverity.LOW,
            InvariantSeverity.MEDIUM,
            InvariantSeverity.HIGH,
            InvariantSeverity.CRITICAL,
        ]
        return max(self.violations, key=lambda v: severity_order.index(v.severity)).severity

    def to_markdown(self) -> str:
        """Format the findings into an Immunefi / responsible disclosure audit report."""
        lines = [
            f"# Formal Invariant Audit Report: {self.target_name}",
            f"**Audit Timestamp:** {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime(self.timestamp))}",
            f"**Execution Latency:** {self.execution_time_ms:.2f} ms | **Lines Scanned:** {self.analyzed_lines}",
            f"**Max Severity:** {self.max_severity.value.upper()}",
            f"**Total Findings:** {len(self.violations)}",
            "",
            "## Executive Summary",
            (
                "Deterministic formal verification detected zero invariant breaches."
                if self.is_clean
                else f"Automated verification identified {len(self.violations)} formal invariant violation(s)."
            ),
            "",
        ]

        if not self.is_clean:
            lines.append("## Detailed Findings & Invariant Proofs")
            for idx, v in enumerate(self.violations, 1):
                lines.extend(
                    [
                        f"### {idx}. [{v.severity.value.upper()}] {v.category.value}: {v.rule_name}",
                        f"- **Line Number:** {v.line_number}",
                        f"- **Description:** {v.description}",
                        "- **Formal Proof Trace:**",
                        f"  ```text\n  {v.formal_proof_trace}\n  ```",
                        f"- **Defensive Remediation:** {v.remediation_recommendation}",
                        "",
                    ]
                )

        lines.extend(
            [
                "---",
                "*Generated by Cohezion AutoHarness Formal Verification Engine (arXiv:2603.03329v1).*",
                "*Strictly for authorized security audits and responsible disclosure programs.*",
            ]
        )
        return "\n".join(lines)


class BugBountyHarness:
    """Formal verification engine scanning for critical invariant violations."""

    def __init__(self, target_name: str = "TargetSystem") -> None:
        self.target_name = target_name

    def audit_python_source(self, code_str: str) -> BountyAuditReport:
        """Audit Python source code deterministically using AST invariant verifiers."""
        t0 = time.perf_counter()
        violations: list[InvariantViolation] = []
        line_count = len(code_str.splitlines())

        try:
            tree = ast.parse(code_str)
            violations.extend(self._verify_access_control(tree))
            violations.extend(self._verify_checks_effects_interactions(tree))
            violations.extend(self._verify_arithmetic_precision(tree))
            violations.extend(self._verify_unbounded_iteration(tree))
        except SyntaxError as e:
            violations.append(
                InvariantViolation(
                    category=InvariantCategory.ACCESS_CONTROL,
                    severity=InvariantSeverity.LOW,
                    rule_name="syntax_integrity",
                    line_number=e.lineno or 0,
                    description=f"Source syntax error preventing full AST parse: {e.msg}",
                    formal_proof_trace="Parser failed to build complete Abstract Syntax Tree.",
                    remediation_recommendation="Ensure code is syntactically valid before verification.",
                )
            )

        dt_ms = (time.perf_counter() - t0) * 1000.0
        return BountyAuditReport(
            target_name=self.target_name,
            analyzed_lines=line_count,
            execution_time_ms=dt_ms,
            violations=violations,
        )

    def _verify_access_control(self, tree: ast.AST) -> list[InvariantViolation]:
        """Detect public state-modifying functions missing authentication/authorization."""
        findings = []
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                # Critical admin or balance modifying method names
                name_lower = node.name.lower()
                is_privileged = any(
                    kw in name_lower
                    for kw in ("set_admin", "withdraw", "transfer_ownership", "drain", "mint")
                )
                if is_privileged and not node.name.startswith("_"):
                    # Check decorators for auth/role checks
                    decorators = [
                        (
                            d.id
                            if isinstance(d, ast.Name)
                            else (d.attr if isinstance(d, ast.Attribute) else "")
                        )
                        for d in node.decorator_list
                    ]
                    has_auth = any(
                        auth_kw in dec.lower()
                        for dec in decorators
                        for auth_kw in (
                            "auth",
                            "admin",
                            "only_owner",
                            "requires_role",
                            "permission",
                        )
                    )
                    if not has_auth:
                        findings.append(
                            InvariantViolation(
                                category=InvariantCategory.ACCESS_CONTROL,
                                severity=InvariantSeverity.CRITICAL,
                                rule_name="unprotected_privileged_state_mutation",
                                line_number=node.lineno,
                                description=(
                                    f"Privileged method '{node.name}' has public visibility but "
                                    "lacks authorization decorators."
                                ),
                                formal_proof_trace=(
                                    f"Function '{node.name}' is callable by any unauthenticated principal.\n"
                                    f"Decorators observed: {decorators or 'None'}\n"
                                    "State transition allows arbitrary caller to alter protocol control."
                                ),
                                remediation_recommendation=(
                                    "Attach explicit authorization gate (e.g., @requires_admin or "
                                    "@requires_role) and enforce caller authentication."
                                ),
                            )
                        )
        return findings

    def _verify_checks_effects_interactions(self, tree: ast.AST) -> list[InvariantViolation]:
        """Detect external/untrusted call interactions occurring before internal state mutations."""
        findings = []
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                external_call_lines: list[int] = []
                for stmt in node.body:
                    # Check if statement contains external dispatch or transfer
                    for sub in ast.walk(stmt):
                        if (
                            isinstance(sub, ast.Call)
                            and isinstance(sub.func, ast.Attribute)
                            and any(
                                kw in sub.func.attr.lower()
                                for kw in ("send", "transfer", "call_external", "dispatch_external")
                            )
                        ):
                            external_call_lines.append(stmt.lineno)

                    # Check if subsequent statement modifies state attributes
                    if external_call_lines and isinstance(stmt, (ast.Assign, ast.AugAssign)):
                        for target in ast.walk(stmt):
                            if (
                                isinstance(target, ast.Attribute)
                                and isinstance(target.value, ast.Name)
                                and target.value.id == "self"
                            ):
                                findings.append(
                                    InvariantViolation(
                                        category=InvariantCategory.CHECKS_EFFECTS_INTERACTIONS,
                                        severity=InvariantSeverity.HIGH,
                                        rule_name="post_call_state_mutation_reentrancy_hazard",
                                        line_number=stmt.lineno,
                                        description=(
                                            f"State mutation to 'self.{target.attr}' at line {stmt.lineno} occurs "
                                            f"after external interaction at line {external_call_lines[0]}."
                                        ),
                                        formal_proof_trace=(
                                            f"Interaction point: Line {external_call_lines[0]}\n"
                                            f"Internal mutation: Line {stmt.lineno} ('self.{target.attr}')\n"
                                            "Invariant violated: Checks-Effects-Interactions (CEI) ordering."
                                        ),
                                        remediation_recommendation=(
                                            "Reorder execution: mutate local state and balances BEFORE invoking "
                                            "external calls, or apply a reentrancy mutex lock."
                                        ),
                                    )
                                )
        return findings

    def _verify_arithmetic_precision(self, tree: ast.AST) -> list[InvariantViolation]:
        """Detect dangerous division before multiplication that induces silent rounding to zero."""
        findings = []
        for node in ast.walk(tree):
            # Check for: (a / b) * c in binary operations
            if (
                isinstance(node, ast.BinOp)
                and isinstance(node.op, ast.Mult)
                and isinstance(node.left, ast.BinOp)
                and isinstance(node.left.op, (ast.Div, ast.FloorDiv))
            ):
                findings.append(
                    InvariantViolation(
                        category=InvariantCategory.ARITHMETIC_PRECISION,
                        severity=InvariantSeverity.MEDIUM,
                        rule_name="division_before_multiplication_precision_loss",
                        line_number=node.lineno,
                        description=(
                            "Arithmetic expression performs division prior to multiplication, "
                            "leading to integer truncation or loss of precision."
                        ),
                        formal_proof_trace=(
                            "AST: BinOp(left=BinOp(op=Div/FloorDiv), op=Mult, right=Expr)\n"
                            "For integer/fixed-point types: (x // y) * z drops fractional remainder, "
                            "yielding 0 when x < y."
                        ),
                        remediation_recommendation=(
                            "Reorder expression to (x * z) // y with appropriate scaling factor "
                            "to preserve mathematical precision."
                        ),
                    )
                )
        return findings

    def _verify_unbounded_iteration(self, tree: ast.AST) -> list[InvariantViolation]:
        """Detect unbounded loops iterating over dynamically sized arguments without bounds."""
        findings = []
        for node in ast.walk(tree):
            if isinstance(node, ast.For) and isinstance(node.iter, ast.Name):
                # Iteration directly over function parameter without length clamp
                findings.append(
                    InvariantViolation(
                        category=InvariantCategory.UNBOUNDED_RESOURCE,
                        severity=InvariantSeverity.LOW,
                        rule_name="unbounded_collection_iteration",
                        line_number=node.lineno,
                        description=(
                            f"Loop iterates over dynamic collection '{node.iter.id}' without explicit upper bound."
                        ),
                        formal_proof_trace=(
                            f"For-loop directly consumes identifier '{node.iter.id}'.\n"
                            "Unbounded collection size presents Denial-of-Service / gas-exhaustion vector."
                        ),
                        remediation_recommendation=(
                            "Assert collection length upper bound (e.g. len(items) <= MAX_BATCH_SIZE) "
                            "or implement paginated processing."
                        ),
                    )
                )
        return findings

    def audit_solidity_source(self, code_or_path: str, contract_name: str = "") -> BountyAuditReport:
        """Audit Solidity contract source code or file path for formal invariant flaws."""
        t0 = time.perf_counter()
        violations: list[InvariantViolation] = []

        code_str = code_or_path
        target = contract_name or self.target_name
        if "\n" not in code_or_path and os.path.isfile(code_or_path):
            target = target or os.path.basename(code_or_path)
            try:
                with open(code_or_path, "r", encoding="utf-8", errors="ignore") as f:
                    code_str = f.read()
            except Exception:
                pass

        lines = code_str.splitlines()

        # 1. Check: State Desynchronization on withdrawal/cancellation paths
        tracking_vars = ["tokenBalanceHistory", "totalDeposits", "trackedBalance", "totalShares", "lockedBalance"]
        active_tracking = [v for v in tracking_vars if v in code_str]

        current_fn = None
        fn_start_line = 0
        sends_token = False
        updates_tracking = False

        for i, line in enumerate(lines, 1):
            line_str = line.strip()
            if line_str.startswith("function ") and ("(" in line_str):
                # Process previous function if exit-type
                if current_fn and sends_token and not updates_tracking and active_tracking:
                    violations.append(
                        InvariantViolation(
                            category=InvariantCategory.STATE_DESYNCHRONIZATION,
                            severity=InvariantSeverity.HIGH,
                            rule_name="unaccounted_token_withdrawal_desynchronization",
                            line_number=fn_start_line,
                            description=(
                                f"Function '{current_fn}' transfers tokens or native assets out of the contract "
                                f"without updating internal tracking state {active_tracking}, causing accounting desynchronization."
                            ),
                            formal_proof_trace=(
                                f"Invariant: balanceNow >= trackingState\n"
                                f"Operation {current_fn}() transfers assets out without state synchronization.\n"
                                f"Resulting state triggers arithmetic underflow Panic(0x11) or DoS on subsequent calls."
                            ),
                            remediation_recommendation=(
                                f"Synchronize tracking state in '{current_fn}' immediately after asset transfer."
                            ),
                        )
                    )

                # Start new function parse
                fn_name = line_str.split("function ")[1].split("(")[0].strip()
                current_fn = fn_name
                fn_start_line = i
                sends_token = False
                updates_tracking = False
            elif current_fn:
                is_exit_fn = any(k in current_fn.lower() for k in ("cancel", "withdraw", "refund", "redeem", "emergency"))
                if is_exit_fn:
                    if any(t in line_str for t in ("_sendToken", "safeTransfer", "transfer(", "call{value:")):
                        sends_token = True
                    if any(v in line_str and "=" in line_str for v in active_tracking):
                        updates_tracking = True

        # Process trailing function
        if current_fn and sends_token and not updates_tracking and active_tracking:
            violations.append(
                InvariantViolation(
                    category=InvariantCategory.STATE_DESYNCHRONIZATION,
                    severity=InvariantSeverity.HIGH,
                    rule_name="unaccounted_token_withdrawal_desynchronization",
                    line_number=fn_start_line,
                    description=(
                        f"Function '{current_fn}' transfers tokens out of the contract without updating "
                        f"internal tracking state {active_tracking}."
                    ),
                    formal_proof_trace=(
                        f"Invariant: balanceNow >= trackingState\n"
                        f"Operation {current_fn}() transfers assets out without state synchronization."
                    ),
                    remediation_recommendation="Synchronize tracking state after asset transfer.",
                )
            )

        # 2. Check: Unprotected Initializer
        for i, line in enumerate(lines, 1):
            if "function initialize(" in line:
                # Find the signature header up to the opening brace '{' or interface semicolon ';'
                sig_window = []
                for lookahead in range(i - 1, min(i + 20, len(lines))):
                    sig_window.append(lines[lookahead])
                    if "{" in lines[lookahead] or ";" in lines[lookahead]:
                        break
                sig_text = " ".join(sig_window)
                if ";" in sig_text and "{" not in sig_text:
                    # Interface declaration
                    continue
                if not any(m in sig_text for m in ("initializer", "onlyOwner", "reinitializer", "onlyInitializing")):
                    violations.append(
                        InvariantViolation(
                            category=InvariantCategory.UNPROTECTED_INITIALIZER,
                            severity=InvariantSeverity.CRITICAL,
                            rule_name="unprotected_initialize_function",
                            line_number=i,
                            description="Function 'initialize' lacks initializer modifier or access control guard.",
                            formal_proof_trace="Any unprivileged caller can invoke initialize() to hijack contract ownership.",
                            remediation_recommendation="Add 'initializer' or 'onlyOwner' modifier to initialize().",
                        )
                    )

        # 3. Check: Capacity Check Operator Inversion / Underflow DoS
        import re
        capacity_or_pattern = re.compile(
            r"if\s*\((?:.+?\.)?(?:maxCapacity|capacity|limit)\s*!=\s*0\s*\|\|\s*(?:.+?)<\s*(?:.+?\.)?(?:maxCapacity|capacity|limit)\)"
        )
        for i, line in enumerate(lines, 1):
            if capacity_or_pattern.search(line):
                violations.append(
                    InvariantViolation(
                        category=InvariantCategory.ARITHMETIC_PRECISION,
                        severity=InvariantSeverity.HIGH,
                        rule_name="capacity_check_operator_inversion_underflow",
                        line_number=i,
                        description=(
                            "Logical OR ('||') used instead of logical AND ('&&') in capacity check, "
                            "permitting saturated or over-allocated execution to proceed to subtraction underflow."
                        ),
                        formal_proof_trace=(
                            "Condition 'maxCapacity != 0 || total < maxCapacity' evaluates to true for ANY non-zero maxCapacity,\n"
                            "bypassing the 'total < maxCapacity' guard. When total >= maxCapacity, subsequent\n"
                            "'maxCapacity - total' triggers an arithmetic underflow Panic(0x11) in Solidity 0.8+,\n"
                            "or returns 0 capacity causing unbounded execution / permanent Denial of Service."
                        ),
                        remediation_recommendation=(
                            "Change logical OR ('||') to logical AND ('&&'): "
                            "'if (info.maxCapacity != 0 && totalStaked < info.maxCapacity)'."
                        ),
                    )
                )

        # 4. Check: Raw Cross-Asset Unit Subtraction
        cross_asset_subtraction_pattern = re.compile(
            r"\((?:totalCollaterals[^\-]*?-\s*totalBorrows[^\)]*?)\)"
        )
        for i, line in enumerate(lines, 1):
            if cross_asset_subtraction_pattern.search(line):
                violations.append(
                    InvariantViolation(
                        category=InvariantCategory.ARITHMETIC_PRECISION,
                        severity=InvariantSeverity.HIGH,
                        rule_name="raw_cross_asset_unit_subtraction",
                        line_number=i,
                        description=(
                            "Direct subtraction between raw collateral and borrow units without "
                            "decimal normalization or oracle price conversion."
                        ),
                        formal_proof_trace=(
                            "Collateral and borrow tokens may have differing decimals (e.g. WBTC 8 vs USDC 6/DAI 18)\n"
                            "and exchange rates. Subtracting raw uint256 units directly causes arithmetic underflow Panic(0x11)\n"
                            "whenever borrow raw units exceed collateral raw units despite adequate economic margin."
                        ),
                        remediation_recommendation=(
                            "Convert borrow amount to collateral asset decimals using price oracle quotes "
                            "before calculating leverage or net equity."
                        ),
                    )
                )

        # 5. Check: Skipped Epoch Rollover State Loss
        epoch_minus_one_pattern = re.compile(
            r"(?:previousEpoch|lastEpoch)\s*=\s*(?:currentEpoch[A-Za-z0-9_]*|\bepoch\b)\s*-\s*1\s*;"
        )
        for i, line in enumerate(lines, 1):
            if epoch_minus_one_pattern.search(line):
                next_window = " ".join(lines[i : min(i + 10, len(lines))])
                if any(k in next_window for k in ("totalUtilization", "systemUtilization", "totalEmissions")):
                    violations.append(
                        InvariantViolation(
                            category=InvariantCategory.STATE_DESYNCHRONIZATION,
                            severity=InvariantSeverity.HIGH,
                            rule_name="skipped_epoch_rollover_state_loss",
                            line_number=i,
                            description=(
                                "System rollover hardcodes 'epoch - 1' lookup without tracking the last active epoch, "
                                "causing cumulative system state to be lost when an epoch is skipped."
                            ),
                            formal_proof_trace=(
                                "System state lookup reads totalUtilization[currentEpoch - 1].\n"
                                "If no transactions occurred in epoch - 1, the mapping returns 0.\n"
                                "The rollover condition fails, resetting total utilization to 0 and driving\n"
                                "subsequent redemptions into negative utilization and distorting emissions."
                            ),
                            remediation_recommendation=(
                                "Track 'lastSystemActiveEpoch' in storage and roll over from "
                                "totalUtilization[lastSystemActiveEpoch] rather than currentEpoch - 1."
                            ),
                        )
                    )

        dt_ms = (time.perf_counter() - t0) * 1000.0
        return BountyAuditReport(
            target_name=target,
            analyzed_lines=len(lines),
            execution_time_ms=dt_ms,
            violations=violations,
        )
