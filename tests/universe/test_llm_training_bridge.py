    @pytest.mark.fast
    def test_trajectory_to_reward_weights(self):
        """[P1] Should respect reward weight configuration."""
        # Different weight configurations
        default_weights = TrajectoryToReward()
        high_hiho = TrajectoryToReward(hiho_weight=0.8, spin_weight=0.1)
        high_spin = TrajectoryToReward(hiho_weight=0.1, spin_weight=0.8)

        # Step with LOW HIHO (far from 0.5) but HIGH spin coherence
        step_high_spin = TrajectoryStep(
            state_12d=[0.9] * 12,  # Far from HIHO
            action="action",
            coherence=0.6,  # Low due to far from HIHO
            spin_coherence=0.95,  # Very high spin
            tempic_field=0.1,
            reward=0.0,
        )

        default_weights.compute_step_reward(step_high_spin)
        hiho_reward = high_hiho.compute_step_reward(step_high_spin)
        spin_reward = high_spin.compute_step_reward(step_high_spin)

        # With high spin weight but low HIHO, should weight spin more heavily
        # High spin config should reward this more than high HIHO config
        assert spin_reward > hiho_reward

        # Step with HIGH HIHO (at 0.5) but LOW spin coherence
        step_high_hiho = TrajectoryStep(
            state_12d=[0.5] * 12,  # At HIHO
            action="action",
            coherence=0.95,  # High due to at HIHO
            spin_coherence=0.2,  # Low spin
            tempic_field=0.1,
            reward=0.0,
        )

        default_weights.compute_step_reward(step_high_hiho)
        hiho_reward2 = high_hiho.compute_step_reward(step_high_hiho)
        spin_reward2 = high_spin.compute_step_reward(step_high_hiho)

        # With high HIHO weight, should get higher reward for HIHO-aligned state
        assert hiho_reward2 > spin_reward2
