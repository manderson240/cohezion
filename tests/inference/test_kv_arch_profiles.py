def test_kv7_ensure_resident_consumes_the_cap_only_when_opted_in(monkeypatch):
    # CONSUMPTION: the ctx that reaches /api/v1/load is the per-model cap, and off by default.
    monkeypatch.setattr(hotswap, "_catalog_sizes", lambda: {"Qwen3.6-35B-A3B-MTP-GGUF": 22.0})
    monkeypatch.setattr(hotswap, "resident_models", lambda: [])
    monkeypatch.setattr(hotswap, "free_gb", lambda: 100.0)
    for opt_in, want in ((False, hotswap.MAX_CTX), (True, 131072)):
        posted = {}
        monkeypatch.setattr(
            hotswap, "_post", lambda p, b, t, _s=posted: _s.update(b) or (200, "ok")
        )
        hotswap.ensure_resident("Qwen3.6-35B-A3B-MTP-GGUF", ctx_size=131072, kv_aware_ctx=opt_in)
        assert posted.get("ctx_size") == want, (opt_in, posted)


def test_kv8_overhead_is_never_looser_than_the_flat_guess():
    for m in ("Qwen3-Coder-Next-GGUF", "Gemma-4-31B-it-GGUF", "Devstral-Small-2507-GGUF"):
        for w in (5.0, 20.0):
            assert hotswap._kv_overhead_gb(w, m, 131072) >= hotswap._kv_overhead_gb(w)
    assert hotswap._kv_overhead_gb(20.0, "Devstral-Small-2507-GGUF", 131072) > 3.0  # dense@128k
