class TestManifoldEquilibrium:
    """[P0] Unit tests for ManifoldEquilibrium."""

    @pytest.fixture()
    def equilibrium(self):
        """Create ManifoldEquilibrium instance."""
        return ManifoldEquilibrium(tolerance=0.05)

    def test_equilibrium_initialization(self):
        """[P0] Should initialize with correct parameters."""
        eq = ManifoldEquilibrium(tolerance=0.1)

        assert eq.target_attractor == 0.5
        assert eq.tolerance == 0.1

    def test_default_tolerance(self):
        """[P1] Should use default tolerance of 0.05."""
        eq = ManifoldEquilibrium()

        assert eq.tolerance == 0.05

    def test_verify_stability_at_exact_attractor(self, equilibrium):
        """[P0] Should verify stability at coherence 1.0."""
        # Coherence 1.0 means dist_from_attractor = 0
        mock_state = MagicMock(spec=AxiomaticState)
        mock_state.coherence_score.return_value = 1.0
        mock_state.logic = 0.5

        result = equilibrium.verify_stability(mock_state)

        assert result["is_stable"] is True
        assert result["coherence"] == 1.0
        assert result["dist_from_attractor"] == 0.0
        assert result["status"] == "EQUILIBRIUM"

    def test_verify_stability_within_tolerance(self, equilibrium):
        """[P0] Should verify stability within tolerance range."""
        # Coherence 0.96 means dist = 0.04 (within tolerance 0.05)
        mock_state = MagicMock(spec=AxiomaticState)
        mock_state.coherence_score.return_value = 0.96
        mock_state.logic = 0.48

        result = equilibrium.verify_stability(mock_state)

        assert result["is_stable"] is True
        assert result["dist_from_attractor"] == pytest.approx(0.04, abs=0.01)
        assert result["status"] == "EQUILIBRIUM"

    def test_verify_stability_outside_tolerance(self, equilibrium):
        """[P0] Should detect entropy when outside tolerance."""
        # Coherence 0.8 means dist = 0.2 (outside tolerance 0.05)
        mock_state = MagicMock(spec=AxiomaticState)
        mock_state.coherence_score.return_value = 0.8
        mock_state.logic = 0.3

        result = equilibrium.verify_stability(mock_state)

        assert result["is_stable"] is False
        assert result["dist_from_attractor"] == pytest.approx(0.2, abs=0.01)
        assert result["status"] == "ENTROPY_DETECTED"

    def test_verify_stability_at_boundary(self, equilibrium):
        """[P1] Should handle boundary conditions."""
        # Test with value clearly within tolerance
        mock_state = MagicMock(spec=AxiomaticState)
        mock_state.coherence_score.return_value = 0.96  # dist = 0.04 from target 1.0
        mock_state.logic = 0.5

        result = equilibrium.verify_stability(mock_state)

        # dist = abs(0.96 - 1.0) = 0.04 <= 0.05 (tolerance)
        assert result["is_stable"] is True
        assert result["dist_from_attractor"] == pytest.approx(0.04, abs=0.001)

    def test_verify_stability_with_different_logic_values(self, equilibrium):
        """[P1] Should capture logic field in result."""
        mock_state = MagicMock(spec=AxiomaticState)
        mock_state.coherence_score.return_value = 1.0
        mock_state.logic = 0.75

        result = equilibrium.verify_stability(mock_state)

        assert result["logic_field"] == 0.75

    def test_validate_trajectory_empty(self, equilibrium):
        """[P0] Should handle empty trajectory."""
        result = equilibrium.validate_trajectory([])

        assert result["trajectory_stability"] == 0
        assert result["converged"] is False
        assert result["sample_count"] == 0

    def test_validate_trajectory_all_stable(self, equilibrium):
        """[P0] Should report high stability for all stable states."""
        states = []
        for _ in range(5):
            mock_state = MagicMock(spec=AxiomaticState)
            mock_state.coherence_score.return_value = 0.98
            states.append(mock_state)

        result = equilibrium.validate_trajectory(states)

        assert result["trajectory_stability"] == 1.0
        assert result["converged"] is True
        assert result["sample_count"] == 5

    def test_validate_trajectory_mixed_stability(self, equilibrium):
        """[P0] Should calculate stability rate correctly."""
        states = []
        # 3 stable, 2 unstable
        for i in range(5):
            mock_state = MagicMock(spec=AxiomaticState)
            # First 3 are stable (high coherence), last 2 are unstable
            mock_state.coherence_score.return_value = 0.98 if i < 3 else 0.8
            states.append(mock_state)

        result = equilibrium.validate_trajectory(states)

        assert result["trajectory_stability"] == pytest.approx(0.6, abs=0.1)
        assert result["converged"] is False  # 0.6 < 0.8 threshold
        assert result["sample_count"] == 5

    def test_validate_trajectory_convergence_threshold(self, equilibrium):
        """[P1] Should report converged when stability > 0.8."""
        states = []
        # 9 stable out of 10 (0.9 > 0.8)
        for i in range(10):
            mock_state = MagicMock(spec=AxiomaticState)
            mock_state.coherence_score.return_value = 0.99 if i < 9 else 0.7
            states.append(mock_state)

        result = equilibrium.validate_trajectory(states)

        assert result["trajectory_stability"] == pytest.approx(0.9, abs=0.05)
        assert result["converged"] is True


