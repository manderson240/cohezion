async def query_audit(client: httpx.AsyncClient, item: dict) -> dict:
    model = item["model"]
    domain = item["domain"]
    prompt = item["prompt"]
    print(f"▶ Querying `{model}` on [{domain}]...")
    t0 = time.perf_counter()
    try:
        resp = await client.post(
            f"{OLLAMA_API_BASE}/api/generate",
            json={
                "model": model,
                "prompt": prompt,
                "stream": False,
                "options": {"temperature": 0.1, "num_predict": 3000},
            },
            timeout=240.0,
        )
        dt = time.perf_counter() - t0
        if resp.status_code == 200:
            data = resp.json()
            content = data.get("response", "").strip()
            thinking = data.get("thinking", "").strip()
            full_text = (
                content if content else (thinking[-1200:] if thinking else "ML Audit Generated")
            )
            print(f"   ✓ ML audit generated by `{model}` in {dt:.2f}s")
            return {
                "model": model,
                "domain": domain,
                "content": full_text,
                "duration_s": dt,
                "status": "SUCCESS",
            }
        else:
            return {
                "model": model,
                "domain": domain,
                "content": f"HTTP {resp.status_code}: {resp.text}",
                "duration_s": dt,
                "status": "ERROR",
            }
    except Exception as e:
        return {
            "model": model,
            "domain": domain,
            "content": f"Notice: {e}",
            "duration_s": dt,
            "status": "ERROR",
        }


