                "# Cell 5: GroupKFold Cross-Validation with Sinkhorn Uniform Balancing\n",
                "def apply_sinkhorn_balancing(probs: np.ndarray, num_iters: int = 5) -> np.ndarray:\n",
                '    """Iteratively normalizes column and row marginals to match uniform P(class) = 1/K."""\n',
