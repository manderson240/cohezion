"""Generate src/cohezion/security/confusables_latin.py from Unicode UTS #39 confusables.txt.

    python scripts/security/gen_confusables_latin.py <path/to/confusables.txt> > src/cohezion/security/confusables_latin.py

Source: https://www.unicode.org/Public/security/latest/confusables.txt (Unicode License v3).
Build-time only: the generated table is vendored, and nothing is fetched at runtime.

Kept: single NON-ASCII code points whose UTS #39 prototype is ONE ASCII letter, minus
every code point that NFKD changes at all (math alphanumerics, fullwidth, ...):
injection_signals applies NFKD first, so such a code point never reaches the table.

Two deliberate departures from the standard, for matching English attack phrases:
* UTS #39 gives every vertical-stroke glyph (Cyrillic І, Greek Ι, dandas, box lines,
  'digit one' forms) the prototype 'l', since I, l, 1 and | share one skeleton. Such a
  stroke may stand for 'i' OR 'l', so their code points are exported separately as
  VERTICAL_STROKES, and the matcher also tries reading them as 'i'.
* SUPPLEMENT: look-alikes UTS #39 does not list but our previous hand table (or the
  2026-10-20 review) did: Greek ε τ χ κ and Cyrillic small-capital-like к м т п.
"""

from __future__ import annotations

import hashlib
import re
import sys
import textwrap
import unicodedata


SUPPLEMENT = {"ε": "e", "τ": "t", "χ": "x", "κ": "k", "к": "k", "м": "m", "т": "t", "п": "n"}


def build(path: str) -> tuple[dict[int, str], set[int], str, str]:
    with open(path, "rb") as fh:
        raw = fh.read()
    text = raw.decode("utf-8-sig")
    version = re.search(r"#\s*Version:\s*(\S+)", text)
    table: dict[int, str] = {}
    strokes: set[int] = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        src, tgt, _ = (x.strip() for x in line.split(";"))
        parts = src.split()
        if len(parts) != 1:
            continue
        cp = int(parts[0], 16)
        target = "".join(chr(int(x, 16)) for x in tgt.split())
        if cp < 0x80 or not (len(target) == 1 and target.isascii() and target.isalpha()):
            continue
        if unicodedata.normalize("NFKD", chr(cp)) != chr(cp):
            continue
        table[cp] = target
        if target in "lI":
            strokes.add(cp)
    for ch, t in SUPPLEMENT.items():
        table.setdefault(ord(ch), t)
    return (
        table,
        strokes,
        version.group(1) if version else "unknown",
        hashlib.sha256(raw).hexdigest(),
    )


def main() -> int:
    table, strokes, version, digest = build(sys.argv[1])
    pairs = " ".join(f"{cp:04x}:{t}" for cp, t in sorted(table.items()))
    stroke_list = " ".join(f"{cp:04x}" for cp in sorted(strokes))
    wrap = lambda s: "\n".join(f'    "{line} "' for line in textwrap.wrap(s, 86))  # noqa: E731
    print(f'''"""Unicode confusables folded to Latin letters. GENERATED; do not edit by hand.

Generated by scripts/security/gen_confusables_latin.py from Unicode UTS #39
confusables.txt, version {version} (sha256 {digest}).
Source: https://www.unicode.org/Public/security/latest/confusables.txt
Copyright (c) Unicode, Inc. Unicode License v3: https://www.unicode.org/license.txt

{len(table)} single code points (prototype = one ASCII letter, NFKD-redundant entries dropped,
plus an 8-entry supplement); {len(strokes)} of them are vertical strokes (see VERTICAL_STROKES).
"""

UTS39_VERSION = "{version}"
UTS39_SHA256 = "{digest}"

_PAIRS = (
{wrap(pairs + " ")}
)
_STROKES = (
{wrap(stroke_list + " ")}
)

CONFUSABLES_TO_LATIN: dict[int, str] = {{
    int(cp, 16): t for cp, t in (p.split(":") for p in _PAIRS.split())
}}
# Code points UTS #39 maps to 'l' or 'I' (one vertical-stroke skeleton). In English
# attack text such a glyph may stand for 'i' as well as 'l'.
VERTICAL_STROKES: frozenset[int] = frozenset(int(cp, 16) for cp in _STROKES.split())''')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
